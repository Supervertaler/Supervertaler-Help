/**
 * The product a page belongs to, from its Starlight entry id (`trados/foo`) or
 * a URL path (`/trados/foo/`). Returns null for the landing page and anything
 * else outside a product tree — those pages stay visible to every scope.
 */
export function productFor(idOrPath: string | undefined | null): Product | null {
  if (!idOrPath) return null;

  const id = idOrPath.replace(/^\/+/, '').replace(/\/+$/, '');
  return (
    PRODUCTS.find((p) => id === p.id || id.startsWith(`${p.id}/`)) ?? null
  );
}

/** Product whose `label` matches, for code that only has the display name. */
export function productByLabel(label: string | null): Product | null {
  if (!label) return null;
  return PRODUCTS.find((p) => p.label === label) ?? null;
}
